/// 字符到频率的映射 (每个字符分配唯一频率，基于语音频段)
///
/// 频率范围: 600 Hz ~ 3400 Hz，覆盖电话语音频段
pub fn char_to_frequency(ch: char) -> f64 {
    match ch {
        '0' => 600.0,
        '1' => 680.0,
        '2' => 760.0,
        '3' => 840.0,
        '4' => 920.0,
        '5' => 1000.0,
        '6' => 1080.0,
        '7' => 1160.0,
        '8' => 1240.0,
        '9' => 1320.0,
        'a' | 'A' => 1400.0,
        'b' | 'B' => 1480.0,
        'c' | 'C' => 1560.0,
        'd' | 'D' => 1640.0,
        'e' | 'E' => 1720.0,
        'f' | 'F' => 1800.0,
        'g' | 'G' => 1880.0,
        'h' | 'H' => 1960.0,
        'i' | 'I' => 2040.0,
        'j' | 'J' => 2120.0,
        'k' | 'K' => 2200.0,
        'l' | 'L' => 2280.0,
        'm' | 'M' => 2360.0,
        'n' | 'N' => 2440.0,
        'o' | 'O' => 2520.0,
        'p' | 'P' => 2600.0,
        'q' | 'Q' => 2680.0,
        'r' | 'R' => 2760.0,
        's' | 'S' => 2840.0,
        't' | 'T' => 2920.0,
        'u' | 'U' => 3000.0,
        'v' | 'V' => 3080.0,
        'w' | 'W' => 3160.0,
        'x' | 'X' => 3240.0,
        'y' | 'Y' => 3320.0,
        'z' | 'Z' => 3400.0,
        _ => 700.0,
    }
}
