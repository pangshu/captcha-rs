/// 成语验证码驱动
///
/// 随机选择一个成语，将其中一个字替换为"口"形成干扰，
/// 用户需输入完整正确成语完成验证。
pub struct DriverIdiom;

impl DriverIdiom {
    pub fn new() -> Self {
        Self
    }
}

impl Default for DriverIdiom {
    fn default() -> Self {
        Self::new()
    }
}

impl Driver for DriverIdiom {
    fn generate(&self) -> Result<(String, String, String)> {
        let mut rng = rand::thread_rng();
        let idx = rng.gen_range(0..IDIOM_LIST.len());
        let idiom: Vec<char> = IDIOM_LIST[idx].chars().collect();
        // 随机选择替换位置 (第 2 或第 3 个字)
        let replace_pos = rng.gen_range(1..=2);
        let mut disturbed = idiom.clone();
        disturbed[replace_pos] = '口';
        let id = random_id();
        let content: String = disturbed.iter().collect();
        let answer = IDIOM_LIST[idx].to_string();
        Ok((id, content, answer))
    }

    fn name(&self) -> &str {
        "DriverIdiom"
    }
}
